import Foundation

// MARK: - Data Model
//
// The bundled `bom_books.json` decodes directly into `BookOfMormon`.
// English verses and crossrefs are loaded lazily by `ScriptureLibrary`
// from their own JSON files.

struct BookOfMormon: Codable, Sendable {
    let books: [Book]
}

struct Book: Codable, Identifiable, Hashable, Sendable {
    let id: String          // e.g. "1nephi", "alma"
    let nameSm: String      // "1 Nifae"
    let nameEn: String      // "1 Nephi"
    let chapters: [Chapter]
}

struct Chapter: Codable, Identifiable, Hashable, Sendable {
    let num: Int
    let verses: [Verse]

    var id: Int { num }
}

struct Verse: Codable, Identifiable, Hashable, Sendable {
    let num: Int
    let words: [WordPair]

    var id: Int { num }

    /// Samoan-only prose, reconstructed by joining word tokens with spaces.
    var samoanText: String {
        words.map(\.sm).joined(separator: " ")
    }
}

struct WordPair: Codable, Hashable, Sendable {
    let sm: String   // Samoan surface form (may include trailing punctuation)
    let en: String   // English gloss — "·" marks "this word continues into the next" for TAM phrases
}

// MARK: - Cross-reference key & entry
//
// Keys in bom_english.json and bom_crossrefs.json look like "1 Nephi|1|1"
// (English book name | chapter | verse).

struct ScriptureKey: Hashable, Sendable {
    let bookEn: String
    let chapter: Int
    let verse: Int

    var raw: String { "\(bookEn)|\(chapter)|\(verse)" }
}

struct CrossRef: Codable, Hashable, Sendable {
    let marker: String     // "a", "b", "c"...
    let text: String       // anchor word
    let refs: [String]     // ["TG Time", "Mosiah 4:2", ...]
    let category: String   // "tg" | "cross-ref" | "trn"
}

// MARK: - Override payload
//
// `bom_overrides.json` is a sparse map of corrected glosses keyed by
// "bookId|chapterNum|verseNum" → full replacement word array.
struct GlossOverrides: Codable, Sendable {
    let version: Int
    let verses: [String: [WordPair]]
}

// MARK: - Diacritic restoration
//
// The published Samoan scriptures use the older unmarked orthography, so the
// bundled text carries almost no macrons (ā ē ī ō ū) or glottal stops. Rather
// than rewrite the official text, `bom_diacritics.json` holds a marked register
// the reader can switch on — useful for learners, since Samoan meaning rides on
// vowel length and the glottal (tama "boy" vs tamā "father").
//
// Generated by `scripts/build_diacritics.py` from `scripts/diacritics_types.tsv`.
struct DiacriticMarks: Codable, Sendable {
    let version: Int
    /// Normalized lowercase form → the same word with diacritics restored.
    let types: [String: String]
    /// `"bookId|chapter|verse|tokenIndex"` → marked form, for words whose
    /// marking depends on context (`mai` "from" vs `ma’i` "sick"). Wins over `types`.
    let exceptions: [String: String]
}

// MARK: - Chapter headings / summaries
//
// `bom_headings.json` holds the editorial chapter summary that sits above
// verse 1, in three registers: verbatim English, verbatim Samoan, and an
// interlinear `words` array (same `·` convention as the verses). Keyed
// "bookId|chapterNum".
struct ChapterHeadings: Codable, Sendable {
    let version: Int
    let headings: [String: HeadingSection]
}

struct HeadingSection: Codable, Hashable, Sendable {
    let en: String
    let sm: String
    let words: [WordPair]?   // interlinear gloss; nil until curated
}

// MARK: - Record-keeper colophons
//
// `bom_colophons.json` holds the sub-record prefaces that precede certain
// chapters (e.g. "O poloaiga a Alema i lona atalii o Helamana. E aofia ai
// mataupu 36 ma le 37."). Keyed "bookId|chapterNum" — the chapter on which the
// colophon appears — and shown above that chapter's summary. Same three
// registers as a heading (`HeadingSection`).
struct Colophons: Codable, Sendable {
    let version: Int
    let colophons: [String: HeadingSection]
}

// MARK: - Front matter
//
// `bom_frontmatter.json` holds the Book of Mormon's front matter (Title Page,
// Introduction, the Witness testimonies, etc.) as an ordered list. Each section
// carries a bilingual title plus body text in three registers: verbatim
// English, verbatim Samoan, and an interlinear `words` array (same `·`
// convention as the verses). `words` is nil until the section is glossed.
struct FrontMatter: Codable, Sendable {
    let version: Int
    let sections: [FrontMatterSection]
}

struct FrontMatterSection: Codable, Hashable, Identifiable, Sendable {
    let id: String          // e.g. "title-page", "introduction"
    let titleEn: String
    let titleSm: String
    let en: String
    let sm: String
    let words: [WordPair]?
}
